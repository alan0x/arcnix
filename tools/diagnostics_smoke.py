        p.get_by_role('button',name='Choose servers and review checks…',exact=True).click()
        expect(p.locator('.form-error')).to_contain_text('warning < critical')
        p.get_by_role('textbox',name='Warning usage (%)',exact=True).fill('85')
        p.get_by_role('textbox',name='Expected TCP ports (optional, comma-separated)',exact=True).fill('22; id')
        p.get_by_role('button',name='Choose servers and review checks…',exact=True).click()
        expect(p.locator('.form-error')).to_contain_text('comma-separated')
        p.get_by_role('textbox',name='Expected TCP ports (optional, comma-separated)',exact=True).fill('22,443')
        p.get_by_role('textbox',name='PEM certificate path (optional)',exact=True).fill('/etc/证书/fullchain.pem')
        p.get_by_role('button',name='Nginx',exact=True).click()
        p.get_by_role('textbox',name='Configuration file (optional; default if empty)',exact=True).fill('/etc/nginx/nginx.conf')
        app.screenshot('checks.png')
        p.get_by_role('button',name='Choose servers and review checks…',exact=True).click()
        d=p.get_by_role('dialog',name='Run script on servers',exact=True)
        d.get_by_role('button',name='Select visible trusted servers',exact=True).click()
        expect(d.locator('.target-choice.active')).to_have_count(2)
        d.get_by_role('button',name='Check targets',exact=True).click()
        expect(p.locator('.task-status')).to_have_text(['Ready','Ready'],timeout=20000)
        for snippet in ['df -P','ss -H -lnt','openssl x509','ARCNIX_DIAG_END_V1']:
            expect(p.locator('.task-target').first).to_contain_text(snippet)
        p.get_by_role('button',name='Execute ready targets',exact=True).click()
        expect(p.locator('.task-status')).to_have_text(['Running','Running'])
        app.stop();time.sleep(4.5);app.launch();p=app.page
        p.locator('.rail-diagnostics').click()
        expect(p.locator('.diagnostic-summary')).to_have_text(['Result unknown','Result unknown'])
        expect(p.locator('.diagnostic-finding')).to_have_count(0)
        p.get_by_role('button',name='View task and raw output',exact=True).click()
