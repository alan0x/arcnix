        expect(p.locator('.diagnostic-critical')).to_have_count(2)
        expect(p.locator('.diagnostic-unknown')).to_have_count(2)
        expect(p.locator('.diagnostic-target').first).to_contain_text('/srv/中文')
        app.screenshot('findings.png')
        p.locator('.diagnostic-target').first.get_by_role('button',name='Measure a directory…',exact=True).click()
