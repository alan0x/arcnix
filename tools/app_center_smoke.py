"""Application-first catalog, source selection and merged installed inventory."""
import json,time,re
from desktop_fixture import Desktop,Peer,ROOT,expect,eventually
from docker_desktop_smoke import seed

def main():
    out=ROOT/'artifacts/app-center'/f'run-{time.time_ns()}';out.mkdir(parents=True)
    local=out/'local';local.mkdir();checks=[]
    with Peer(out/'ubuntu') as ubuntu,Peer(out/'fedora') as fedora:
        (ubuntu.root/'docker-fixture.json').write_text(json.dumps(seed()))
        (ubuntu.root/'software-snap-enabled').touch()
        (fedora.root/'software-manager').write_text('dnf')
        no_systemd = ubuntu.profile('Ubuntu without systemd')
        no_systemd['username'] = 'arcnix-nosystemd'
        config=ubuntu.config([ubuntu.profile('Ubuntu applications'),fedora.profile('Fedora applications'),no_systemd],local)
        config['config']['trusted_hosts']+=fedora.config([],local)['config']['trusted_hosts']
        with Desktop(out/'desktop',config) as app:
            p=app.page;errors=[];p.on('pageerror',lambda e:errors.append(str(e)))
            def card(name):return p.locator('.app-center-app-card').filter(has=p.get_by_role('button',name=name,exact=True))
            def install(name):
                card(name).get_by_role('button',name='Install…',exact=True).click()
                return p.get_by_role('dialog',name='Install software',exact=True)
            def close(d):d.get_by_role('button',name='Close dialog',exact=True).click();expect(d).not_to_be_visible()
            app.connect();app.application('App Center')
            expect(p.locator('.app-center-app-card')).to_have_count(18)
            expect(p.locator('.install-sources')).to_have_count(0)
            expect(p.locator('.software-sources')).to_have_count(0)
            expect(p.locator('.app-center-featured')).to_be_visible()
            app.screenshot('app-center-light.png')
            p.locator('.app-center-categories').get_by_role('button',name='Databases',exact=True).click();expect(p.locator('.app-center-app-card')).to_have_count(4)
            p.locator('.app-center-categories').get_by_role('button',name='All applications',exact=True).click()
            p.get_by_role('textbox',name='Search applications',exact=True).fill('restic');expect(p.locator('.app-center-app-card')).to_have_count(1)
            card('restic').get_by_role('button',name='restic',exact=True).click();expect(p.locator('.app-center-detail')).to_contain_text('Encrypted snapshots')
            expect(p.locator('.app-center-detail .app-center-website')).to_have_text('https://restic.net/')
            expect(p.locator('.install-sources')).to_have_count(0)
            p.get_by_role('textbox',name='Search applications',exact=True).fill('unfindable-application');expect(p.locator('.app-center-empty')).to_be_visible()
            p.get_by_role('textbox',name='Search applications',exact=True).fill('')
            checks.append('Catalog shows 18 application cards, categories, search, product details and an empty state without exposing provider tabs during browsing')

            d=install('Caddy');expect(d.locator('.install-app-name')).to_have_text('Caddy')
            for source in ['System packages','Snap','Docker Compose']:expect(d.get_by_role('button',name=source,exact=True)).to_be_enabled()
            d.get_by_role('button',name='Snap',exact=True).click();expect(d.locator('.install-package-name')).to_have_text('caddy');expect(d).to_contain_text('aoilinux')
            d.get_by_role('button',name='Docker Compose',exact=True).click();expect(d.get_by_role('textbox',name='Container image',exact=True)).to_have_value('caddy:2-alpine')
            expect(d.get_by_role('textbox',name='Project name',exact=True)).to_have_value('caddy')
            app.screenshot('caddy-methods.png');close(d)
            d=install('Git');expect(d.get_by_role('button',name='Snap',exact=True)).to_be_disabled();expect(d.get_by_role('button',name='Docker Compose',exact=True)).to_be_disabled();expect(d).to_contain_text('No Compose template');close(d)
            d=install('Certbot');d.get_by_role('button',name='Snap',exact=True).click();expect(d.get_by_role('button',name='Install',exact=True)).to_be_disabled()
            d.get_by_role('checkbox',name='Allow classic confinement',exact=True).check();expect(d.get_by_role('button',name='Install',exact=True)).to_be_enabled();close(d)
            checks.append('Install opens app-specific provider cards; supported sources carry correct names/images and publisher, unsupported sources are disabled, and classic confinement requires an explicit choice')

            p.locator('.app-center-navigation').get_by_role('button',name='Installed',exact=True).click()
            p.get_by_role('checkbox',name='Show all system packages',exact=True).check()
            expect(p.locator('.app-center-inventory-list')).to_contain_text('curl')
            expect(p.locator('.app-center-installed-row').filter(has_text='curl').locator('.app-center-source-badge')).to_have_text('APT')
            p.locator('.app-center-installed-row').filter(has_text='curl').get_by_role('button',name='Upgrade…',exact=True).click()
            task=p.get_by_role('dialog',name='Upgrade software',exact=True);expect(task).to_contain_text('curl · APT');task.get_by_role('button',name='Cancel',exact=True).click()
            p.locator('.app-center-installed-row').filter(has_text='curl').get_by_role('button',name='Remove…',exact=True).click()
            task=p.get_by_role('dialog',name='Remove software',exact=True);expect(task).to_contain_text('curl · APT');task.get_by_role('button',name='Cancel',exact=True).click()
            app.servers();app.application('Docker');p.locator('.docker-toolbar').get_by_role('button',name='Install software',exact=True).click()
            expect(p.locator('.app-center-content')).to_be_visible();expect(p.locator('.app-center-app-card')).to_have_count(3);expect(p.get_by_role('dialog')).to_have_count(0)
            d=install('Nginx');expect(d.get_by_role('button',name='Docker Compose',exact=True)).to_have_attribute('aria-pressed','true');close(d)
            p.get_by_role('button',name='Show all applications',exact=True).click();expect(p.locator('.app-center-app-card')).to_have_count(18)
            checks.append('Installed inventory retains source-specific management, while Docker installation enters the same catalog with Compose-compatible apps and opens provider choice only after Install')

            result=p.get_by_role('dialog',name='Operation status',exact=True)
            dependency_flag=ubuntu.root/'installer-dependency-upgrade'
            dependency_flag.touch()
            d=install('Nginx');d.get_by_role('button',name='Install',exact=True).click()
            expect(result.locator('.task-status')).to_have_text('Failed',timeout=25000)
            expect(result).to_contain_text('Installation requires changes to installed packages')
            expect(p.locator('.rail-servers')).to_have_class(re.compile(r'\bactive\b'))
            result.get_by_role('button',name='Back to installation',exact=True).click()
            expect(d.locator('.install-app-name')).to_have_text('Nginx')
            d.get_by_role('button',name='Installation options',exact=True).click()
            d.get_by_role('checkbox',name='Review dependency upgrades',exact=True).check()
            d.get_by_role('button',name='Review package changes…',exact=True).click()
            expect(result.locator('.task-status')).to_have_text('Ready',timeout=25000)
            expect(result).to_contain_text('Inst dependency [1.0]')
            expect(result.get_by_role('button',name='Apply package changes',exact=True)).to_be_enabled()
            result.get_by_role('button',name='Cancel',exact=True).click()
            dependency_flag.unlink()
            d=install('Nginx');d.get_by_role('button',name='Install',exact=True).click()
            expect(result.locator('.task-status')).to_have_text('Succeeded',timeout=25000)
            expect(result.locator('.installation-report')).to_contain_text('Installation checks passed')
            expect(p.locator('.rail-servers')).to_have_class(re.compile(r'\bactive\b'))
            result.get_by_role('button',name='Query server result',exact=True).click()
            query=p.get_by_role('dialog',name='Query server result',exact=True)
            expect(p.locator('.desktop-modal-backdrop')).to_have_count(1)
            query.get_by_role('button',name='Query',exact=True).click()
            expect(result.locator('.task-status')).to_have_text('Succeeded')
            close(result)
            p.locator('.app-center-navigation').get_by_role('button',name='Installed',exact=True).click()
            expect(p.locator('.app-center-inventory-list')).to_contain_text('nginx')
            checks.append('APT installation starts directly, confirms dependency changes only when requested, and refreshes the inventory on completion inside Desktop')

            p.locator('.host-select').nth(2).click();app.connect(2);app.application('App Center')
            d=install('Nginx');d.get_by_role('button',name='Install',exact=True).click()
            expect(result.locator('.task-status')).to_have_text('Failed',timeout=25000)
            expect(result).to_contain_text('The operation did not start. This server needs a running systemd system manager and systemd-run.')
            expect(p.locator('.rail-servers')).to_have_class(re.compile(r'\bactive\b'))
            expect(result.get_by_role('button',name='Query server result',exact=True)).to_have_count(0)
            close(result)
            checks.append('On servers without systemd, Desktop shows why the installation could not start')
            p.locator('.rail-tasks').click()
            expect(p.locator('.task-heading')).to_have_count(4)
            expect(p.locator('.rail-tasks')).to_have_class(re.compile(r'\bactive\b'))
            app.servers()

            p.locator('.host-select').nth(1).click();app.connect(1);app.application('App Center')
            d=install('PostgreSQL');expect(d.locator('.install-package-name')).to_have_text('postgresql-server');expect(d.locator('.install-provider')).to_contain_text('DNF')
            expect(d.get_by_role('button',name='Snap',exact=True)).to_be_disabled();close(d)
            d=install('htop');expect(d.get_by_role('button',name='Snap',exact=True)).to_be_disabled();expect(d).to_contain_text('Requires Snap');close(d)
            app.application('Settings');settings=p.locator('.desktop-settings-page');settings.get_by_role('button',name='Desktop',exact=True).click();settings.get_by_role('button',name='Dark',exact=True).click();expect(settings.get_by_role('button',name='Dark',exact=True)).to_have_attribute('aria-pressed','true');app.application('App Center')
            expect(p.locator('.app')).to_have_class('app theme-light')
            app.screenshot('app-center-dark.png')
            for width in [1100,900]:
                p.set_viewport_size(dict(width=width,height=800));assert p.evaluate('document.documentElement.scrollWidth <= innerWidth')
                app.screenshot(f'app-center-dark-{width}.png')
            p.set_viewport_size(dict(width=1440,height=980))
            app.settings('General');p.get_by_role('button',name='简体中文',exact=True).click();app.servers()
            p.get_by_role('textbox',name='搜索应用',exact=True).fill('数据库');expect(p.locator('.app-center-app-card')).to_have_count(4)
            p.get_by_role('textbox',name='搜索应用',exact=True).fill('');app.screenshot('app-center-chinese.png')
            assert not errors,errors
            checks.append('Fedora uses distro-specific package identities, missing runtimes remain unavailable, and light/dark, Chinese search and narrow layouts preserve desktop theme boundaries')
    (out/'results.json').write_text(json.dumps(checks,indent=2));print(json.dumps(dict(output=str(out),checks=checks),indent=2))

if __name__=='__main__':main()
