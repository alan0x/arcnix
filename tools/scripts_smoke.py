"""Exercise global scripts, bounded multi-host preflight, and server-owned recovery."""
from pathlib import Path
import json, time
from desktop_fixture import Peer, Desktop, expect, ROOT
out = ROOT/'artifacts/scripts-ui'
out.mkdir(parents=True, exist_ok=True)
with Peer(out/'peer-a') as a, Peer(out/'peer-b') as b:
    profiles=[a.profile('Alpha'), b.profile('Beta'), b.profile('No systemd')]
    profiles[-1]['username']='arcnix-nosystemd'
    config=a.config(profiles,out)
    host,port=b.data['address'].rsplit(':',1)
    config['config']['trusted_hosts'].append(dict(host=host,port=int(port),fingerprint=b.data['host_key_rsa_fingerprint']))
    config['config']['snippets']=[dict(id='mine',name='My parameter script',description='Reusable user script',command="printf '%s\\n' {{message}}",administrator=False)]
    with Desktop(out/f'desktop-{time.time_ns()}',config) as app:
        p=app.page
        expect(p.locator('.navigation-rail button')).to_have_count(7)
        assert p.locator('.navigation-rail button').evaluate_all("xs=>xs.map(x=>x.className)")[0].find('rail-servers')>=0
        p.locator('.rail-scripts').click()
        expect(p.locator('.script-row')).to_have_count(11)
        expect(p.locator('.module-nav')).to_have_count(0)
        app.screenshot('official-scripts.png')
        p.locator('.script-row').filter(has_text='Install Nginx').get_by_role('button',name='Run on servers…',exact=True).click()
        d=p.get_by_role('dialog',name='Run script on servers',exact=True)
        d.locator('.target-choice').nth(0).click()
        d.locator('.target-choice').nth(1).click()
        d.get_by_role('button',name='Check targets',exact=True).click()
        expect(p.locator('.task-target')).to_have_count(2)
        expect(p.locator('.task-status')).to_have_text(['Ready','Ready'])
        expect(p.locator('.task-target').first).to_contain_text('Inst nginx')
        expect(p.get_by_role('button',name='Execute ready targets',exact=True)).to_be_enabled()
        app.screenshot('preflight-plans.png')
        p.get_by_role('button',name='Execute ready targets',exact=True).click()
        expect(p.locator('.task-status')).to_have_text(['Running','Running'])
        app.stop()
        time.sleep(4.5)
        app.launch();p=app.page
        p.locator('.rail-tasks').click()
        p.locator('.task-heading').first.click()
        expect(p.locator('.task-status')).to_have_text(['Result unknown','Result unknown'])
        for index in range(2):
            p.locator('.task-target').nth(index).get_by_role('button',name='Query server result',exact=True).click()
            p.get_by_role('dialog',name='Query server result',exact=True).get_by_role('button',name='Query',exact=True).click()
            expect(p.locator('.task-status').nth(index)).to_have_text('Succeeded')
            expect(p.locator('.task-target').nth(index)).to_contain_text('Server-owned fixture job finished')
        app.screenshot('recovered-results.png')
        p.locator('.rail-scripts').click()
        p.locator('.context-links').get_by_role('button',name='My scripts',exact=True).click()
        expect(p.locator('.script-row')).to_have_count(1)
        p.get_by_role('button',name='Run on servers…',exact=True).click()
        d=p.get_by_role('dialog',name='Run script on servers',exact=True)
        d.get_by_role('textbox',name='message',exact=True).fill("hello '; $(id) {{message}}")
        d.locator('.target-choice').nth(0).click()
        d.locator('.target-choice').nth(2).click()
        d.get_by_role('button',name='Check targets',exact=True).click()
        expect(p.locator('.task-status')).to_have_text(['Ready','Failed'])
        expect(p.locator('.task-target').first).to_contain_text("hello '\\''; $(id) {{message}}")
        p.get_by_role('button',name='Stop pending targets',exact=True).click()
        expect(p.locator('.task-status')).to_have_text(['Cancelled','Failed'])
        p.locator('.rail-scripts').click()
        p.get_by_role('button',name='New script',exact=True).click()
        d=p.get_by_role('dialog',name='Save command',exact=True)
        d.get_by_role('textbox',name='Command name',exact=True).fill('Saved from global library')
        d.get_by_role('textbox',name='Shell command',exact=True).fill('echo hello')
        d.get_by_role('button',name='Save command',exact=True).click()
        expect(p.locator('.script-row')).to_have_count(2)
        app.servers();app.connect()
        p.get_by_role('button',name='Operations',exact=True).click();p.get_by_role('button',name='Commands',exact=True).click()
        p.locator('.snippet-row').filter(has_text='My parameter script').get_by_role('button',name='Run command…',exact=True).click()
        d=p.get_by_role('dialog',name='Run script on servers',exact=True)
        expect(d.get_by_role('textbox',name='message',exact=True)).to_be_visible()
        expect(d.locator('.target-choice.active')).to_have_count(1)
        d.get_by_role('button',name='Cancel',exact=True).click()
        p.locator('.rail-scripts').click()
        p.set_viewport_size(dict(width=900,height=700))
        assert p.evaluate('document.documentElement.scrollWidth <= innerWidth')
        app.screenshot('scripts-narrow.png')
        app.settings('General')
        p.locator('.setting-language:visible').get_by_role('radio', name='简体中文', exact=True).check()
        expect(p.locator('.page-header-title')).to_have_text('常规')
        p.locator('.rail-scripts').click()
        expect(p.locator('.page-header-title')).to_have_text('运维脚本')
        app.screenshot('scripts-chinese.png')
        data=json.loads(app.config.read_text())
        assert 'fixture-admin-secret' not in json.dumps(data)
        history=json.loads(app.config.with_suffix('.tasks.json').read_text())
        assert len(history)==2
        assert all(t['status']=='Succeeded' for t in history[1]['targets'])
(out/'results.json').write_text(json.dumps(dict(passed=True,checks=['global navigation','official and custom scripts','multi-server preflight','APT plan preview','server job survives desktop exit','restart query without resubmission','unsupported system preflight','literal parameter expansion','cancel pending targets','global script create','narrow layout','Chinese locale','parameterized command entry uses the global parameter form']),indent=2))
print('13 global scripts desktop checks passed')
