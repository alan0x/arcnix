        entry=dict(id=identifier,modified=1700000000+number,state='inactive',code=0,metadata=metadata,log='Saved log · 中文\n')
        if number==0:entry.update(metadata=None,state='not-found',code=None,log='旧任务 中文 arcnix-test\nARCNIX_RECORD_LOG_V1\n仍然可读\n')
        if number==109:metadata['name']='private arcnix-test name'
        if number==108:entry.update(state='active',code=0)
        if number==107:entry.update(state='unavailable',code=0)
        if number==106:entry.update(state='failed',code=0)
        if number==105:entry.update(state='deactivating',code=None)
        if number==104:metadata['id']='forged-record';metadata['name']='Do not trust this forged title'
